-- Проверяем, существует ли таблица Документы
-- Если существует, скрипт выдаст ошибку при попытке создания
-- В этом случае можно закомментировать блок CREATE TABLE

-- ========================================================================
-- СОЗДАНИЕ ТАБЛИЦЫ ДОКУМЕНТОВ
-- ========================================================================

CREATE TABLE IF NOT EXISTS Документы (
    id_документа INTEGER PRIMARY KEY AUTOINCREMENT,
    vk_id INTEGER NOT NULL,
    тип_документа TEXT DEFAULT 'общий', -- 'служебка', 'переговорка', 'медиапроект', 'общий'
    id_заявки INTEGER, -- ID связанной заявки (опционально)
    vk_doc_id INTEGER NOT NULL, -- ID документа в VK
    vk_owner_id INTEGER NOT NULL, -- Owner ID документа в VK
    название_файла TEXT NOT NULL,
    расширение TEXT,
    размер INTEGER, -- размер в байтах
    url TEXT NOT NULL,
    дата_загрузки TEXT DEFAULT (datetime('now', 'localtime')),
    FOREIGN KEY (vk_id) REFERENCES Пользователь(vk_id)
);

-- ========================================================================
-- СОЗДАНИЕ ИНДЕКСОВ ДЛЯ ОПТИМИЗАЦИИ
-- ========================================================================

CREATE INDEX IF NOT EXISTS IX_Документы_vk_id ON Документы(vk_id);
CREATE INDEX IF NOT EXISTS IX_Документы_тип ON Документы(тип_документа);
CREATE INDEX IF NOT EXISTS IX_Документы_дата ON Документы(дата_загрузки);

-- ========================================================================
-- ПРОВЕРКА УСПЕШНОСТИ СОЗДАНИЯ
-- ========================================================================

SELECT '✅ Таблица Документы успешно создана!' AS Статус;

-- Показать структуру таблицы
PRAGMA table_info(Документы);

-- Подсчитать существующие документы (должно быть 0 при первом запуске)
SELECT COUNT(*) AS Количество_документов FROM Документы;

SELECT '✅ Обновление базы данных завершено!' AS Результат;
