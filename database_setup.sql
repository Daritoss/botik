-- ========================================================================
-- БАЗА ДАННЫХ ДЛЯ VK БОТА (SQLite версия)
-- Полная объединенная структура с поддержкой служебок, переговорок и медиапроектов
-- ========================================================================
--
-- ВАЖНО! ПЕРЕД ЗАПУСКОМ СКРИПТА:
-- 1. В SQLite Studio: Database → Add a database (Ctrl+O)
-- 2. Создайте файл базы данных, например: vkbot.db
-- 3. Выберите созданную базу в левой панели
-- 4. Tools → Open SQL Editor (Alt+E)
-- 5. Вставьте этот скрипт и нажмите F9 (Execute query)
--
-- СТРУКТУРА:
-- • 1 таблица пользователей
-- • 3 справочника (служебки, переговорки, оборудование)
-- • 4 таблицы заявок (служебки, переговорки, медиапроекты, диалоги)
-- • 2 служебные таблицы (история сообщений, статистика)
-- • 1 связующая таблица (оборудование в переговорках)
-- ========================================================================

-- ========================================================================
-- 1. ПОЛЬЗОВАТЕЛИ
-- ========================================================================

CREATE TABLE Пользователь (
    vk_id INTEGER PRIMARY KEY,
    имя TEXT,
    фамилия TEXT,
    дата_регистрации TEXT DEFAULT (datetime('now', 'localtime')),
    последняя_активность TEXT DEFAULT (datetime('now', 'localtime')),
    активен INTEGER DEFAULT 1
);

-- ========================================================================
-- 2. ДИАЛОГИ (для отслеживания сессий и состояний пользователя)
-- ========================================================================

CREATE TABLE Диалог (
    id_диалога INTEGER PRIMARY KEY AUTOINCREMENT,
    vk_id INTEGER NOT NULL,
    дата_начала TEXT DEFAULT (datetime('now', 'localtime')),
    последнее_сообщение TEXT,
    состояние_диалога TEXT,
    FOREIGN KEY (vk_id) REFERENCES Пользователь(vk_id)
);

-- ========================================================================
-- 3. СПРАВОЧНИК СЛУЖЕБОК
-- ========================================================================

CREATE TABLE Служебки (
    id_служебки INTEGER PRIMARY KEY AUTOINCREMENT,
    тип_служебки TEXT NOT NULL, -- 'аудитория', 'освобождение', 'пропуск'
    инструкция TEXT,
    шаблон_файл TEXT -- путь к файлу шаблона
);

-- ========================================================================
-- 4. ЗАЯВКИ НА СЛУЖЕБКИ
-- ========================================================================

CREATE TABLE Заявка_на_служебку (
    id_заявки INTEGER PRIMARY KEY AUTOINCREMENT,
    id_диалога INTEGER,
    vk_id INTEGER NOT NULL,
    дата_мероприятия TEXT,
    дата_подачи TEXT DEFAULT (datetime('now', 'localtime')),
    id_служебки INTEGER NOT NULL,
    статус TEXT DEFAULT 'В обработке', -- 'В обработке', 'Одобрено', 'Отклонено'
    файл_прикреплен INTEGER DEFAULT 0,
    комментарии TEXT,
    дата_обработки TEXT,
    FOREIGN KEY (id_диалога) REFERENCES Диалог(id_диалога),
    FOREIGN KEY (vk_id) REFERENCES Пользователь(vk_id),
    FOREIGN KEY (id_служебки) REFERENCES Служебки(id_служебки)
);

-- ========================================================================
-- 5. СПРАВОЧНИК ПЕРЕГОВОРОК
-- ========================================================================

CREATE TABLE Переговорки (
    id_переговорки INTEGER PRIMARY KEY AUTOINCREMENT,
    название TEXT NOT NULL,
    вместимость INTEGER
);

-- ========================================================================
-- 6. СПРАВОЧНИК ОБОРУДОВАНИЯ
-- ========================================================================

CREATE TABLE Оборудование (
    id_оборудования INTEGER PRIMARY KEY AUTOINCREMENT,
    название TEXT NOT NULL,
    количество INTEGER DEFAULT 1,
    примечание TEXT
);

-- ========================================================================
-- 7. СВЯЗЬ: ОБОРУДОВАНИЕ В ПЕРЕГОВОРКАХ (многие-ко-многим)
-- ========================================================================

CREATE TABLE Оборудование_в_переговорке (
    id_переговорки INTEGER NOT NULL,
    id_оборудования INTEGER NOT NULL,
    PRIMARY KEY (id_переговорки, id_оборудования),
    FOREIGN KEY (id_переговорки) REFERENCES Переговорки(id_переговорки),
    FOREIGN KEY (id_оборудования) REFERENCES Оборудование(id_оборудования)
);

-- ========================================================================
-- 8. ЗАЯВКИ НА ПЕРЕГОВОРКИ
-- ========================================================================

CREATE TABLE Заявки_на_переговорки (
    id_заявки INTEGER PRIMARY KEY AUTOINCREMENT,
    id_диалога INTEGER,
    vk_id INTEGER NOT NULL,
    название_мероприятия TEXT NOT NULL,
    формат TEXT, -- 'онлайн', 'офлайн', 'гибрид'
    количество_человек INTEGER,
    дата_и_время TEXT NOT NULL,
    необходимость_оборудования TEXT,
    id_оборудования INTEGER,
    id_переговорки INTEGER,
    дата_подачи TEXT DEFAULT (datetime('now', 'localtime')),
    статус TEXT DEFAULT 'Подтверждено', -- 'Подтверждено', 'Отменено'
    FOREIGN KEY (id_диалога) REFERENCES Диалог(id_диалога),
    FOREIGN KEY (vk_id) REFERENCES Пользователь(vk_id),
    FOREIGN KEY (id_оборудования) REFERENCES Оборудование(id_оборудования),
    FOREIGN KEY (id_переговорки) REFERENCES Переговорки(id_переговорки)
);

-- ========================================================================
-- 9. ЗАЯВКИ НА МЕДИАПРОЕКТЫ
-- ========================================================================

CREATE TABLE Заявка_на_медиапроект (
    id_заявки INTEGER PRIMARY KEY AUTOINCREMENT,
    id_диалога INTEGER,
    vk_id INTEGER NOT NULL,
    название TEXT NOT NULL,
    формат TEXT, -- 'видео', 'статья', 'подкаст', 'инфографика' и т.д.
    необходимая_поддержка TEXT,
    место_публикации TEXT,
    описание TEXT,
    дата_подачи TEXT DEFAULT (datetime('now', 'localtime')),
    статус TEXT DEFAULT 'На рассмотрении', -- 'На рассмотрении', 'Одобрено', 'Отклонено'
    дата_рассмотрения TEXT,
    id_куратора INTEGER,
    комментарии TEXT,
    FOREIGN KEY (id_диалога) REFERENCES Диалог(id_диалога),
    FOREIGN KEY (vk_id) REFERENCES Пользователь(vk_id)
);

-- ========================================================================
-- 10. ИСТОРИЯ СООБЩЕНИЙ (для аналитики и отладки)
-- ========================================================================

CREATE TABLE История_сообщений (
    id_сообщения INTEGER PRIMARY KEY AUTOINCREMENT,
    vk_id INTEGER NOT NULL,
    текст_сообщения TEXT,
    ответ_бота TEXT,
    время TEXT DEFAULT (datetime('now', 'localtime')),
    состояние_пользователя TEXT,
    FOREIGN KEY (vk_id) REFERENCES Пользователь(vk_id)
);

-- ========================================================================
-- 11. СТАТИСТИКА (дневная сводка)
-- ========================================================================

CREATE TABLE Статистика (
    id_статистики INTEGER PRIMARY KEY AUTOINCREMENT,
    дата TEXT DEFAULT (date('now', 'localtime')),
    количество_служебок INTEGER DEFAULT 0,
    количество_броней INTEGER DEFAULT 0,
    количество_медиапроектов INTEGER DEFAULT 0,
    количество_активных_пользователей INTEGER DEFAULT 0,
    количество_сообщений INTEGER DEFAULT 0
);

-- ========================================================================
-- 12. ТАБЛИЦА ДОКУМЕНТОВ (для хранения загруженных файлов)
-- ========================================================================

CREATE TABLE Документы (
    id_документа INTEGER PRIMARY KEY AUTOINCREMENT,
    vk_id INTEGER NOT NULL,
    тип_документа TEXT, -- 'служебка', 'переговорка', 'медиапроект', 'общий'
    id_заявки INTEGER, -- ID связанной заявки (опционально)
    vk_doc_id INTEGER NOT NULL, -- ID документа в VK
    vk_owner_id INTEGER NOT NULL, -- Owner ID документа в VK
    название_файла TEXT NOT NULL,
    расширение TEXT,
    размер INTEGER, -- размер в байтах
    url TEXT NOT NULL,
    дата_загрузки TEXT DEFAULT (datetime('now', 'localtime')),
    FOREIGN KEY (vk_id) REFERENCES Пользователь(vk_id)
);

-- ========================================================================
-- 13. ЗАНЯТОСТЬ PLAYSTATION (слоты)
-- ========================================================================

CREATE TABLE Занятость_PlayStation (
    id_слота INTEGER PRIMARY KEY AUTOINCREMENT,
    дата TEXT NOT NULL,
    время_начала TEXT NOT NULL,
    время_окончания TEXT NOT NULL,
    vk_id INTEGER NOT NULL,
    id_заявки INTEGER,
    статус TEXT DEFAULT 'Занято',
    дата_обновления TEXT DEFAULT (datetime('now', 'localtime')),
    FOREIGN KEY (vk_id) REFERENCES Пользователь(vk_id)
);

-- ========================================================================
-- ИНДЕКСЫ (для оптимизации запросов)
-- ========================================================================

-- Индексы для заявок на служебки
CREATE INDEX IX_Заявка_служебка_vk_id ON Заявка_на_служебку(vk_id);
CREATE INDEX IX_Заявка_служебка_статус ON Заявка_на_служебку(статус);
CREATE INDEX IX_Заявка_служебка_дата ON Заявка_на_служебку(дата_подачи);

-- Индексы для заявок на переговорки
CREATE INDEX IX_Заявка_переговорка_vk_id ON Заявки_на_переговорки(vk_id);
CREATE INDEX IX_Заявка_переговорка_дата ON Заявки_на_переговорки(дата_и_время);
CREATE INDEX IX_Заявка_переговорка_статус ON Заявки_на_переговорки(статус);

-- Индексы для медиапроектов
CREATE INDEX IX_Медиапроект_vk_id ON Заявка_на_медиапроект(vk_id);
CREATE INDEX IX_Медиапроект_статус ON Заявка_на_медиапроект(статус);
CREATE INDEX IX_Медиапроект_дата ON Заявка_на_медиапроект(дата_подачи);

-- Индексы для истории сообщений
CREATE INDEX IX_История_vk_id ON История_сообщений(vk_id);
CREATE INDEX IX_История_время ON История_сообщений(время);

-- Индексы для диалогов
CREATE INDEX IX_Диалог_vk_id ON Диалог(vk_id);

-- Индексы для документов
CREATE INDEX IX_Документы_vk_id ON Документы(vk_id);
