-- ========================================================================
-- ПРЕДСТАВЛЕНИЯ (готовые SQL-запросы)
-- ========================================================================

-- Сводка активности пользователей
CREATE VIEW Сводка_активности_пользователей AS
SELECT 
    п.vk_id,
    п.имя,
    п.фамилия,
    п.дата_регистрации,
    п.последняя_активность,
    COUNT(DISTINCT зс.id_заявки) AS количество_служебок,
    COUNT(DISTINCT зп.id_заявки) AS количество_броней,
    COUNT(DISTINCT зм.id_заявки) AS количество_медиапроектов,
    COUNT(DISTINCT ис.id_сообщения) AS количество_сообщений
FROM Пользователь п
LEFT JOIN Заявка_на_служебку зс ON п.vk_id = зс.vk_id
LEFT JOIN Заявки_на_переговорки зп ON п.vk_id = зп.vk_id
LEFT JOIN Заявка_на_медиапроект зм ON п.vk_id = зм.vk_id
LEFT JOIN История_сообщений ис ON п.vk_id = ис.vk_id
GROUP BY п.vk_id, п.имя, п.фамилия, п.дата_регистрации, п.последняя_активность;

-- Предстоящие брони переговорок
CREATE VIEW Предстоящие_брони AS
SELECT 
    зп.id_заявки,
    п.vk_id,
    п.имя,
    п.фамилия,
    зп.название_мероприятия,
    зп.дата_и_время,
    пер.название AS переговорка,
    зп.количество_человек,
    зп.необходимость_оборудования
FROM Заявки_на_переговорки зп
INNER JOIN Пользователь п ON зп.vk_id = п.vk_id
LEFT JOIN Переговорки пер ON зп.id_переговорки = пер.id_переговорки
WHERE зп.дата_и_время > datetime('now', 'localtime')
  AND зп.статус = 'Подтверждено';

